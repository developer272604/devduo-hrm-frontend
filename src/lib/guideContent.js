export function guideFor(pathname) {
  return GUIDE.filter((g) => (g.exact ? pathname === g.prefix : pathname === g.prefix || pathname.startsWith(`${g.prefix}/`))).sort(
    (a, b) => b.prefix.length - a.prefix.length,
  )[0];
}
