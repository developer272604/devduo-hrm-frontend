import React from 'react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { WorkflowGeneratorCard, resolveStep } from './WorkflowGeneratorCard';
import { api } from '../../lib/api';

vi.mock('../../lib/api', () => ({ api: vi.fn(), query: (o) => new URLSearchParams(o).toString() }));

const generated = (questions = []) => ({
  generation_uuid: 'g1',
  language: 'english',
  name_suggestion: 'Joiner setup',
  warnings: [],
  spec: {
    trigger: { type: 'event', event_type: 'EmployeeCreated' },
    steps: [{ title: 'Assign a laptop', action: 'task', assignment: 'fixed', assignees: [], mode: 'any', timeout_hours: 48 }],
  },
  steps: [{ title: 'Assign a laptop', action: 'task', matched: [], assignee_names: [], confidence: questions.length ? 'needs_input' : 'high' }],
  questions,
  limitations: 'Generated by a keyword-based interpreter without an AI model.',
});
const q = [{ step: 1, question: 'Who is responsible?', candidates: [{ id: 5, name: 'Hema Nair' }] }];
const ui = () =>
  render(
    <MemoryRouter>
      <WorkflowGeneratorCard />
    </MemoryRouter>,
  );
afterEach(cleanup);
beforeEach(() => vi.resetAllMocks());

it('resolveStep assigns the chosen person and clears only that question without mutating the input', () => {
  const r = generated(q);
  const next = resolveStep(r, 1, { id: 5, name: 'Hema Nair' });
  expect(next.spec.steps[0].assignees).toEqual([5]);
  expect(next.questions).toEqual([]);
  expect(r.spec.steps[0].assignees).toEqual([]);
});

it('keeps saving blocked until every question is answered, then saves the reviewed spec as a draft', async () => {
  api.mockImplementation((path) => Promise.resolve(path.endsWith('/generate') ? generated(q) : { uuid: 'd1' }));
  ui();
  fireEvent.change(screen.getByLabelText('What should happen?'), { target: { value: 'When a new employee joins, assign a laptop' } });
  fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));
  expect(await screen.findByText(/Who is responsible\?/)).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Save as draft' })).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Hema Nair' }));
  fireEvent.click(await screen.findByRole('button', { name: 'Save as draft' }));
  await waitFor(() =>
    expect(api).toHaveBeenCalledWith(
      expect.stringContaining('/generations/g1/draft'),
      expect.objectContaining({ method: 'POST', body: expect.objectContaining({ name: 'Joiner setup' }) }),
    ),
  );
  expect(await screen.findByText(/Another administrator must publish it/)).toBeInTheDocument();
});

it('states plainly that no AI model is used', async () => {
  api.mockResolvedValue(generated());
  ui();
  fireEvent.change(screen.getByLabelText('What should happen?'), { target: { value: 'When a new employee joins, assign a laptop' } });
  fireEvent.click(screen.getByRole('button', { name: 'Generate draft' }));
  expect(await screen.findByText(/without an AI model/)).toBeInTheDocument();
});
